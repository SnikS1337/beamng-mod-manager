/**
 * Проверка архива идёт асинхронно. Пока она шла, человек мог открыть другой мод:
 * ответ по прошлому архиву тогда — чужой. Раньше он заполнял панель нового мода,
 * а в пачке и вовсе откладывался под его страницей и ставился вместо него.
 */
export class StaleGuard {
  #current = 0;

  /** Новая проверка: всё, что началось раньше, больше не считается. */
  begin(): number {
    return ++this.#current;
  }

  isCurrent(token: number): boolean {
    return token === this.#current;
  }
}
